# Builds ESP32_LOCALSRV\settings_pages.h from the four settings pages: the three bench pages (Box 1, Box 2, ACS) and the new Box 3 page.
# Each page keeps its own JavaScript; only the endpoint prefix, the title, the nav bar and (ACS) the unit selector change.
$ErrorActionPreference = 'Stop'
$proj = 'C:\Users\Administrator\Documents\Arduino\ESP32 Project'
$sp   = $PSScriptRoot   # folder of this script: box3_page.html lives next to it
$utf8 = New-Object System.Text.UTF8Encoding($false)

function RawOf($path) {
  $t = [System.IO.File]::ReadAllText($path, $utf8)
  $m = [regex]::Match($t, 'R"rawliteral\((.*)\)rawliteral"', 'Singleline')
  if (-not $m.Success) { throw "no raw string in $path" }
  return $m.Groups[1].Value
}
function Sub1($text, $pattern, $replacement, $what) {
  $rx = New-Object System.Text.RegularExpressions.Regex($pattern, 'Singleline')
  $n = $rx.Matches($text).Count
  if ($n -ne 1) { throw "expected exactly 1 match for '$what' but found $n" }
  return $rx.Replace($text, [System.Text.RegularExpressions.MatchEvaluator]{ param($m) $replacement })
}

$navCss = '.hubnav{display:flex;gap:6px;flex-wrap:wrap;margin:0 0 10px}.hubnav a{color:#9ad;text-decoration:none;border:1px solid #444;border-radius:8px;padding:6px 10px;font-size:13px}.hubnav a.cur{background:#1e4f8a;color:#fff;border-color:#59f}'
function Nav($cur) {
  $items = @(@('/', 'home', '&larr; Control Center'), @('/box1', 'box1', 'Box 1'), @('/box2', 'box2', 'Box 2'), @('/box3', 'box3', 'Box 3'), @('/acs', 'acs', 'ACS 1 / 2'))
  $h = '<div class="hubnav">'
  foreach ($i in $items) { $c = ''; if ($i[1] -eq $cur) { $c = ' class="cur"' }; $h += '<a' + $c + ' href="' + $i[0] + '">' + $i[2] + '</a>' }
  return $h + '</div>'
}

function Build($html, $cur, $api, $title, $h1, $noteText) {
  $h = $html
  $h = Sub1 $h '<title>.*?</title>' "<title>$title</title>" 'title'
  $h = Sub1 $h '<h1>[^<]*<span id="net"' "<h1>$h1 <span id=`"net`"" 'h1'
  if ($noteText) { $h = Sub1 $h '<div class="note">A stand-in[^<]*</div>' "<div class=`"note`">$noteText</div>" 'standin note' }
  $h = Sub1 $h '</style>' "$navCss</style>" 'style end'
  $h = Sub1 $h '<body>' ('<body>' + (Nav $cur)) 'body'
  $h = Sub1 $h '<script>' "<script>`nconst API='$api';" 'script start'
  return $h
}

# ---- Box 1 ----
$b1 = RawOf "$proj\ESP32_S3A_CONFIG_BENCH\config_page.h"
$b1 = Build $b1 'box1' '/api/b1' 'Box 1 Settings' 'Box 1 settings' "Changes the S3A's saved settings over the air; the S3A keeps them in its own memory, so nothing is lost when this board is switched off."
$b1 = Sub1 $b1 'fetch\(u,' 'fetch(API+u,' 'box1 fetch'
$b1 = $b1.Replace('send the request to the ACS', 'send the request to ACS 1')

# ---- Box 2 ----
$b2 = RawOf "$proj\ESP32_S3C_CONFIG_BENCH\config_page.h"
$b2 = Build $b2 'box2' '/api/b2' 'Box 2 Settings' 'Box 2 settings &middot; Heater' "Changes the S3C's saved settings over the air; the S3C keeps them in its own memory, so nothing is lost when this board is switched off."
$b2 = Sub1 $b2 'fetch\(u,' 'fetch(API+u,' 'box2 fetch'

# ---- Box 3 (hand-written page) ----
$b3 = [System.IO.File]::ReadAllText("$sp\box3_page.html", $utf8)
$b3 = Sub1 $b3 '</style>' "$navCss</style>" 'b3 style end'
$b3 = Sub1 $b3 '<body>' ('<body>' + (Nav 'box3')) 'b3 body'
$b3 = Sub1 $b3 '<script>' "<script>`nconst API='/api/b3';" 'b3 script start'
$b3 = Sub1 $b3 'fetch\(u,' 'fetch(API+u,' 'box3 fetch'

. (Join-Path $PSScriptRoot 'screen_section.ps1')   # AddScreenSection: force-refresh button + per-relay refresh table (2026-10-03)
$b1 = AddScreenSection $b1 ''
$b2 = AddScreenSection $b2 ''
$b3 = AddScreenSection $b3 ' and when the heater switches on or off'
# ---- ACS ----
$ac = RawOf "$proj\ESP32_ACS_CONFIG_BENCH\config_page.h"
$ac = Build $ac 'acs' '/api/acs' 'ACS Settings' 'ACS settings &middot; refill systems' "Changes the ACS's saved settings over the air; each ACS keeps them in its own memory. Pick ACS 1 (Box 1) or ACS 2 (Box 3) below - everything on this page then talks to that one."
$ac = Sub1 $ac 'fetch\(u,' "fetch(API+u+(u.indexOf('?')>=0?'&':'?')+'u='+UNIT," 'acs fetch'
$ac = Sub1 $ac "function pick\(n\)\{dirty=\{levels:false,timing:false,mix:false\};loaded=\{levels:'',timing:'',mix:''\};q\('/unit\?v='\+n\);\}" "function pick(n){UNIT=n;dirty={levels:false,timing:false,mix:false};loaded={levels:'',timing:'',mix:''};q('/state');}" 'acs pick'
$ac = Sub1 $ac 'const API=''/api/acs'';' "const API='/api/acs';let UNIT=1;" 'acs unit var'

$out = New-Object System.Text.StringBuilder
[void]$out.AppendLine('// GENERATED by build_hub_pages.ps1 (2026-10-03) from the S3A / S3C / ACS bench pages and the new Box 3 page - do not edit by hand.')
[void]$out.AppendLine('// Each settings page talks to the LocalServer under /api/b1, /api/b2, /api/b3 and /api/acs (see settings_hub.h).')
[void]$out.AppendLine('#pragma once')
[void]$out.AppendLine('#include <Arduino.h>')
foreach ($p in @(@('PAGE_BOX1', $b1), @('PAGE_BOX2', $b2), @('PAGE_BOX3', $b3), @('PAGE_ACS', $ac))) {
  if ($p[1].Contains(')hubpage"')) { throw 'page contains the raw-string terminator' }
  [void]$out.AppendLine('const char ' + $p[0] + '[] PROGMEM = R"hubpage(' + $p[1] + ')hubpage";')
}
[System.IO.File]::WriteAllText("$proj\ESP32_LOCALSRV\settings_pages.h", $out.ToString(), $utf8)
"written: " + (Get-Item "$proj\ESP32_LOCALSRV\settings_pages.h").Length + " bytes (box1 $($b1.Length), box2 $($b2.Length), box3 $($b3.Length), acs $($ac.Length))"

